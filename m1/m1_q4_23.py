ip_address = '192.168.3.1'
ip_spl = ip_address.split('.') # ['192', '168', '3', '1']
bin_exp = ''
for num in ip_spl:
    bin_exp += bin(int(num))[2:] + '.'
print(bin_exp[:-1])

'''メモ
splitメソッドは引数で指定された文字列で分割し、リストを作る
bin()関数とは2進数の文字列に変換する
int()関数とは文字列を整数に変換する
スライスについて[2:]はインデックス2以降を取得する
スライスについて[:-1]は末尾の１文字を取り除いて取得する
'''