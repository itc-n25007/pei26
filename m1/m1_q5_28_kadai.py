
# 曜日のリストを作成する
days = ['月', '月', '火', '水', '木', '金', '金']

# 重複している最初の「月」を1つ削除する
days.remove('月')  # 指定した値と一致する最初の要素を削除する

# 重複している最初の「金」を1つ削除する
days.remove('金')  # 「金」の重複分を1つ削除する

# リストの先頭に「日」を追加する
days.insert(0, '日')  # インデックス0の位置に「日」を挿入する

# リストの末尾に「土」を追加する
days.insert(6, '土')  # インデックス6の位置に「土」を挿入する

# 完成したリストを表示する
print(days)
